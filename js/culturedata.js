/*
 * Allows other YUGMA files to safely retrieve information.
 */

window.getYugmaCultureData = function(stateId) {

  if (!stateId) {
    return null;
  }

  const normalizedId =
    String(stateId)
      .trim()
      .toLowerCase()
      .replace(/&/g, 'and')
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '');

  return window.YUGMA_CULTURE_DATA[
    normalizedId
  ] || null;
};


